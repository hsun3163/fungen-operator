"""Generate a genuinely executed, clearly labelled synthetic lifecycle via MCP."""

import asyncio
from pathlib import Path

from mcp import Client
from mcp.types import ElicitResult

from .actions import PrepareConfig, CheckReadiness, InitiateRun
from .fixture import create_fixture
from .harness import Harness
from .notebook import Notebook
from .server import create_server


async def lifecycle(deployment, *, with_interruption=True):
    harness = Harness(deployment)
    server = create_server(harness)
    approvals = []

    async def simulated_human(ctx, params):
        approvals.append(params.message)
        return ElicitResult(action="accept", content={"approve": True})

    args = dict(notebook=str(Path(deployment.run_root, "operator.ipynb")),
                configfile=str(Path(deployment.run_root, "config.yaml")),
                workdir=str(Path(deployment.run_root, "work")))
    calls = []
    async with Client(server, elicitation_callback=simulated_human) as client:
        async def call(name, model):
            result = await client.call_tool(name, {"request": model.model_dump()})
            if result.is_error:
                raise RuntimeError(str(result))
            calls.append({"tool": name, **result.structured_content})
            return result.structured_content

        await call("prepare_config", PrepareConfig(**args))
        await call("prepare_config", PrepareConfig(**args, parameters={"pca.n_pcs": 1}))
        run = {**args, "log_dir": str(Path(deployment.run_root, "logs")), "targets": ["all"]}
        await call("check_readiness", CheckReadiness(**run))
        if with_interruption:
            Path(deployment.conda_env, "interrupt-next").touch()
        first = await call("initiate_run", InitiateRun(**run))
        await client.call_tool("inspect_run", {"request": {"notebook": args["notebook"]}})
        if with_interruption:
            await call("initiate_run", InitiateRun(**run))
        final = await call("check_readiness", CheckReadiness(**run, phase="conclusion"))
    book = Notebook(args["notebook"])
    nb = book.read()
    nb.cells[0].source = (
        "# Fungen Operator: executed synthetic lifecycle\n\n"
        "**Backend: synthetic fixture. These are not real LSF receipts or genomic results.**\n\n"
        "The MCP client supplied a simulated human approval for changing `pca.n_pcs` from 20 to 1. "
        "The first submission deliberately stopped after producing one file; the second used the "
        "same action and workspace, reused that file, and finished. Final canonical-form readiness "
        "reported nothing remaining. Superseded config/submission attempts keep their outputs below.\n\n"
        "Prerequisites (fixture checkout, runtime, and deployment) were generated by "
        "`fungen-operator demo --root <new-directory>`. Regenerate in a new directory on another machine. "
        "Replay with `fungen-operator replay --deployment <root>/deployment.json "
        "--notebook <root>/runs/operator.ipynb`; use the history-aware replay command, not Run All."
    )
    nb.metadata.fungen["synthetic_approval"] = True
    book.save(nb)
    return {"notebook": args["notebook"], "approval_requests": len(approvals),
            "initial_scheduler_state": first["scheduler"]["status"],
            "final_status": final["status"], "calls": calls}


def run_demo(root: Path):
    return asyncio.run(lifecycle(create_fixture(root)))
