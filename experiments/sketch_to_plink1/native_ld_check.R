args <- commandArgs(trailingOnly = TRUE)
if (length(args) != 3L) stop("usage: native_ld_check.R PREFIX INDEX_TSV OUTPUT_TSV")
suppressPackageStartupMessages(library(pecotmr))
idx <- as.integer(read.delim(args[[2]], header = FALSE)[[1]])
p <- pecotmr:::open_pgen(paste0(args[[1]], ".pgen"))
on.exit(pgenlibr::ClosePgen(p), add = TRUE)
x <- pecotmr:::read_pgen(p, idx, meanimpute = FALSE)
R <- pecotmr:::compute_LD(x)
write.table(R, args[[3]], sep = "\t", quote = FALSE, col.names = NA)
